export function auditTone(action: string): 'danger' | 'warning' | 'neutral' | 'success' {
  if (/login_failed|account_locked|deleted|deactivated|anonymized|withdrawn/.test(action)) return 'danger';
  if (/password|session_revoked|export|downloaded|viewed|clinical\.read/.test(action)) return 'warning';
  if (/created|published|login$/.test(action)) return 'success';
  return 'neutral';
}

/** Bilinmeyen eylemler için okunur yedek: "client.foo_bar" → "client · foo bar" */
export function auditLabel(action: string) {
  return AUDIT_ACTION_LABEL[action] ?? action.replace('.', ' · ').replace(/_/g, ' ');
}
